import { copyFile, mkdir, readdir, rm, stat, writeFile } from "node:fs/promises";
import { dirname, relative, resolve } from "node:path";
import {
  displayPath,
  guidelineFiles,
  knowledgeRoot,
  repoRoot,
  sandboxKnowledgeRoot,
  verifyKnowledge,
} from "./knowledge.mjs";

const generatedRoot = resolve(repoRoot, "generated");
const manifest = await verifyKnowledge();
const activeSources = manifest.sources.filter((source) => source.status === "approved");
const files = [...(await guidelineFiles())];

for (const source of activeSources) {
  const snapshot = resolve(repoRoot, source.snapshotPath);
  files.push(snapshot);
  files.push(resolve(dirname(snapshot), "provenance.json"));
}

const agentRoots = [];
for (const name of await readdir(resolve(repoRoot, "agents"))) {
  // Phase 2 leaves the Stage 4 Planning Agent untouched, including its packaged knowledge.
  if (name === "planning") continue;
  const marker = resolve(repoRoot, "agents", name, "agent/sandbox/sandbox.ts");
  try {
    if ((await stat(marker)).isFile()) {
      agentRoots.push(resolve(repoRoot, "agents", name, "agent/sandbox/workspace/knowledge"));
    }
  } catch {
    // Reserved names such as a future factory agent have no sandbox yet.
  }
}
if (agentRoots.length === 0) agentRoots.push(sandboxKnowledgeRoot);

let preparedFileCount = 0;
for (const outputRoot of agentRoots) {
  await rm(outputRoot, { force: true, recursive: true });
  await mkdir(outputRoot, { recursive: true });
  for (const source of files) {
    const destinationPath = relative(knowledgeRoot, source);
    if (destinationPath.startsWith("..") || destinationPath.includes("projects/") || destinationPath.includes("fixtures/")) {
      throw new Error(`Refusing to package ${displayPath(source)} into the sandbox.`);
    }
    const destination = resolve(outputRoot, destinationPath);
    await mkdir(dirname(destination), { recursive: true });
    await copyFile(source, destination);
    preparedFileCount += 1;
  }
}

const runtimeManifest = {
  schemaVersion: manifest.schemaVersion,
  status: manifest.status,
  precedence: manifest.precedence,
  sources: activeSources.map((source) => ({
    id: source.id,
    title: source.title,
    origin: source.origin,
    capturedAt: source.capturedAt,
    snapshotPath: source.snapshotPath,
    priority: source.priority,
    status: source.status,
    usage: source.usage,
  })),
};

for (const outputRoot of agentRoots) {
  await writeFile(
    resolve(outputRoot, "manifest.json"),
    `${JSON.stringify(runtimeManifest, null, 2)}\n`,
  );
  preparedFileCount += 1;
}

await mkdir(generatedRoot, { recursive: true });
await writeFile(
  resolve(generatedRoot, "config.ts"),
  `// Generated by scripts/prepare-knowledge.mjs. Do not edit.
interface SpecificationAgentConfig {
  readonly status: "draft" | "approved";
  readonly knowledgeOwnerSlackId: string | null;
  readonly allowedChannelIds: readonly string[];
  readonly allowedUserIds: readonly string[];
}

export const specificationConfig: SpecificationAgentConfig = ${JSON.stringify(
    {
      status: manifest.status,
      knowledgeOwnerSlackId: manifest.agent.knowledgeOwnerSlackId,
      allowedChannelIds: manifest.agent.allowedChannelIds,
      allowedUserIds: manifest.agent.allowedUserIds,
    },
    null,
    2,
  )};

export const factoryConfig = specificationConfig;
`,
);

console.log(
  `Prepared ${preparedFileCount} knowledge files for ${agentRoots.length} agent sandbox${agentRoots.length === 1 ? "" : "es"}. Project directories and fixtures were not packaged.`,
);
